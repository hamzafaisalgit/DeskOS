export function makeApp(
  id: string,
  name: string,
  description: string,
  html: string,
  js: string,
  capabilities: Capability[] = [],
  category = "Utilities",
  icon = "\u25c7",
): AppPackage {
  const manifest = {
    format: "deskos-app" as const,
    packageVersion: 1 as const,
    id,
    name,
    version: "1.0.0",
    description,
    developer: "DeskOS Studio",
    category,
    icon,
    entrypoint: "index.html" as const,
    sdk: 1 as const,
    capabilities,
    fileTypes: [] as string[],
    multiple: false,
    keywords: [name.toLowerCase(), category.toLowerCase()],
  };
  return {
    manifest,
    files: {
      "manifest.json": JSON.stringify(manifest, null, 2),
      "index.html": `<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="styles.css"></head><body><h1>${name}</h1><p>${description}</p>${html}<script src="app.js"></script></body></html>`,
      "styles.css": baseStyle,
      "app.js": themeCode + js,
    },
  };
}
